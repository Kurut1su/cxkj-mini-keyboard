"""Windows scan codes (set 1, as Qt's nativeScanCode() reports them) to HID keyboard usages.

HID keycodes are positional, like scan codes, so capturing by scan code gives the right key
whatever keyboard layout Windows uses. Extended keys carry 0x100, as in Qt on Windows.
"""

EXTENDED = 0x100

# Scan code -> modifier bit.
MODIFIER_SCANCODES = {
    0x1D: 0x01,             # Left Ctrl
    0x2A: 0x02,             # Left Shift
    0x38: 0x04,             # Left Alt
    EXTENDED | 0x5B: 0x08,  # Left Win
    EXTENDED | 0x1D: 0x10,  # Right Ctrl
    0x36: 0x20,             # Right Shift
    EXTENDED | 0x38: 0x40,  # Right Alt (AltGr)
    EXTENDED | 0x5C: 0x80,  # Right Win
}

SCANCODE_TO_HID: dict[int, int] = {
    0x01: 0x29,  # Esc
    0x0C: 0x2D, 0x0D: 0x2E, 0x0E: 0x2A, 0x0F: 0x2B,  # - = Backspace Tab
    0x1A: 0x2F, 0x1B: 0x30, 0x1C: 0x28,  # [ ] Enter
    0x27: 0x33, 0x28: 0x34, 0x29: 0x35, 0x2B: 0x31,  # ; ' ` \
    0x33: 0x36, 0x34: 0x37, 0x35: 0x38,  # , . /
    0x37: 0x55, 0x39: 0x2C, 0x3A: 0x39,  # Num* Space CapsLock
    0x45: 0x48, 0x46: 0x47,  # Pause ScrollLock
    0x47: 0x5F, 0x48: 0x60, 0x49: 0x61, 0x4A: 0x56,  # Num7 Num8 Num9 Num-
    0x4B: 0x5C, 0x4C: 0x5D, 0x4D: 0x5E, 0x4E: 0x57,  # Num4 Num5 Num6 Num+
    0x4F: 0x59, 0x50: 0x5A, 0x51: 0x5B, 0x52: 0x62, 0x53: 0x63,  # Num1 Num2 Num3 Num0 Num.
    0x56: 0x64,  # ISO key next to Left Shift (<> on Spanish keyboards)
    0x57: 0x44, 0x58: 0x45,  # F11 F12
    0x76: 0x73,  # F24
    EXTENDED | 0x1C: 0x58,  # NumEnter
    EXTENDED | 0x35: 0x54,  # Num/
    EXTENDED | 0x37: 0x46,  # PrintScreen
    EXTENDED | 0x45: 0x53,  # NumLock
    EXTENDED | 0x47: 0x4A, EXTENDED | 0x48: 0x52, EXTENDED | 0x49: 0x4B,  # Home Up PageUp
    EXTENDED | 0x4B: 0x50, EXTENDED | 0x4D: 0x4F,  # Left Right
    EXTENDED | 0x4F: 0x4D, EXTENDED | 0x50: 0x51, EXTENDED | 0x51: 0x4E,  # End Down PageDown
    EXTENDED | 0x52: 0x49, EXTENDED | 0x53: 0x4C,  # Insert Delete
    EXTENDED | 0x5D: 0x65,  # Menu
}
# Number row 1..0.
SCANCODE_TO_HID.update({0x02 + i: 0x1E + i for i in range(10)})
# Letter rows, in physical order.
for first_scancode, letters in ((0x10, "QWERTYUIOP"), (0x1E, "ASDFGHJKL"), (0x2C, "ZXCVBNM")):
    SCANCODE_TO_HID.update({first_scancode + i: 0x04 + ord(c) - ord("A") for i, c in enumerate(letters)})
# F1..F10, F13..F23.
SCANCODE_TO_HID.update({0x3B + i: 0x3A + i for i in range(10)})
SCANCODE_TO_HID.update({0x64 + i: 0x68 + i for i in range(11)})
